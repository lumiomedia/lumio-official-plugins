import { describe, expect, it, vi } from 'vitest'
import { fireEvent, screen, waitFor, within } from '@testing-library/react'
import { localDayKey, shiftDay } from '../sport-epg'
import { getOverrides, getSportSettings } from '../sport-store'
import { HOUR, MIN, fxMatch, mountSport } from '../__sport-fixture'

vi.mock('../../live-tv-player', () => ({ LiveTvPlayer: ({ channel }: { channel: { name: string } }) => <div data-testid="player">{channel.name}</div> }))

const now = Date.now()
const today = localDayKey(now)
const live = fxMatch({ id: 'live', home: 'GAIS', away: 'Sirius', start: now - 30 * MIN, stop: now + 90 * MIN })
const later = fxMatch({ id: 'later', home: 'AIK', away: 'Hammarby', start: now + 2 * HOUR })
const shl = fxMatch({ id: 'shl', kind: 'hockey', league: 'SHL', leagueKey: 'shl', home: 'HV71', away: 'Brynäs', start: now + 3 * HOUR })

describe('Sportskalet', () => {
  it('rubrik med sammanfattning, hero, exakt en data-init', async () => {
    mountSport({}, { days: { [today]: [live, later] } })
    expect(await screen.findByTestId('sport-hero')).toHaveTextContent('GAIS')
    expect(screen.getByTestId('sport-summary')).toHaveTextContent('Today · 2 matches · 1 live · 2 on your channels')
    expect(document.querySelectorAll('[data-init]')).toHaveLength(1)
  })
  it('Resultat-fliken finns (tre flikar) och visar nyckelkortet utan nyckel, aldrig som banner', async () => {
    mountSport({}, { days: { [today]: [live, later] } })
    await screen.findByTestId('sport-hero')
    expect(['foryou', 'results', 'follows'].map((k) => screen.queryByTestId(`sport-tab-${k}`) !== null)).toEqual([true, true, true])
    expect(screen.queryByTestId('sport-key-card-banner')).toBeNull()
    expect(screen.queryByTestId('sport-key-card-tab')).toBeNull()
    fireEvent.click(screen.getByTestId('sport-tab-follows'))
    expect(screen.queryByTestId('sport-key-card-banner')).toBeNull()
    fireEvent.click(screen.getByTestId('sport-tab-results'))
    expect(await screen.findByTestId('sport-key-card-tab')).toBeInTheDocument()
    expect(screen.queryByTestId('sport-key-card-banner')).toBeNull()
  })
  it('Visa som Flöde sparas i sportinställningarna', async () => {
    mountSport({}, { days: { [today]: [live, later] } })
    await screen.findByTestId('sport-hero')
    fireEvent.click(screen.getByText('Feed'))
    expect(getSportSettings().view).toBe('feed')
    expect(await screen.findByTestId('feed-teams')).toBeInTheDocument()
  })
  it('dagstegaren: › hämtar morgondagen, längre fram går inte; ‹ tillbaka till idag', async () => {
    const { fetchSpy } = mountSport({}, { days: { [today]: [live] } })
    await screen.findByTestId('sport-hero')
    expect(screen.getByTestId('sport-day-label')).toHaveTextContent('Today')
    fireEvent.click(screen.getByTestId('sport-day-next'))
    expect(await screen.findByTestId('sport-empty')).toBeInTheDocument()
    expect(screen.getByTestId('sport-summary')).toHaveTextContent('Tomorrow · 0 matches · 0 live · 0 on your channels')
    expect(screen.getByTestId('sport-day-next').getAttribute('aria-disabled')).toBe('true')
    fireEvent.click(screen.getByTestId('sport-day-next'))
    expect(screen.getByTestId('sport-day-label')).toHaveTextContent('Tomorrow')
    fireEvent.click(screen.getByTestId('sport-day-prev'))
    expect(screen.getByTestId('sport-day-label')).toHaveTextContent('Today')
    const days = fetchSpy.mock.calls.map((call) => new URL(String(call[0]), 'http://localhost').searchParams.get('day'))
    expect(days).toContain(shiftDay(today, 1))
  })
  it('sportchips som textpiller med antal, bara sporter med matcher; valt = vit pill; Alla återställer', async () => {
    mountSport({}, { days: { [today]: [live, later, shl] } })
    await screen.findByTestId('sport-hero')
    expect(screen.getByTestId('sport-chip-all')).toHaveTextContent('All')
    expect(screen.getByTestId('sport-chip-all').getAttribute('aria-pressed')).toBe('true')
    expect(screen.getByTestId('sport-chip-football')).toHaveTextContent('Football2')
    expect(screen.getByTestId('sport-chip-hockey')).toHaveTextContent('Ice hockey1')
    expect(screen.queryByTestId('sport-chip-tennis')).toBeNull()
    fireEvent.click(screen.getByTestId('sport-chip-hockey'))
    await waitFor(() => expect(screen.getByTestId('sport-summary')).toHaveTextContent('Today · 1 matches'))
    expect(screen.getByTestId('sport-chip-hockey').getAttribute('aria-pressed')).toBe('true')
    fireEvent.click(screen.getByTestId('sport-chip-all'))
    await waitFor(() => expect(screen.getByTestId('sport-summary')).toHaveTextContent('Today · 3 matches'))
  })
  it('Mina lag: "N lag och turneringar" och klocktipset; flikarna heter Översikt / Tabeller & resultat / Mina lag', async () => {
    mountSport({}, { days: { [today]: [live] } })
    await screen.findByTestId('sport-hero')
    expect(screen.getByTestId('sport-tab-results')).toHaveTextContent('Tables & results')
    fireEvent.click(screen.getByTestId('sport-tab-follows'))
    expect(screen.getByTestId('sport-follows-meta')).toHaveTextContent('0 teams and competitions')
    expect(screen.getByTestId('sport-follows-meta')).toHaveTextContent('Use the bell to choose reminders')
  })
  it('EN fokusmarkering: Sport-ytan tar bort kontrollernas egen kant och skuggor medan fokusringen syns', async () => {
    mountSport({}, { days: { [today]: [live] } })
    await screen.findByTestId('sport-hero')
    const css = [...document.querySelectorAll('style')].map((s) => s.textContent ?? '').join('\n')
    expect(css).toMatch(/\[data-sport-stage\] \[data-f\]:focus[^{]*\{ box-shadow: none !important; border-color: transparent !important; \}/)
    expect(screen.getByTestId('sport-stage').hasAttribute('data-sport-stage')).toBe(true)
  })
  it('dagstegaren går att stega med pilarna: ‹ och › är varandras grannar, OK stegar dagen (Jerry 2026-10-11)', async () => {
    mountSport({}, { days: { [today]: [live] } })
    await screen.findByTestId('sport-hero')
    const prev = screen.getByTestId('sport-day-prev')
    const next = screen.getByTestId('sport-day-next')
    expect(document.querySelector(prev.getAttribute('data-f-right')!)).toBe(next)
    expect(document.querySelector(next.getAttribute('data-f-left')!)).toBe(prev)
    expect(next.getAttribute('tabindex')).toBe('0')
    fireEvent.keyDown(next, { key: 'Enter' })
    expect(screen.getByTestId('sport-day-label')).toHaveTextContent('Tomorrow')
    fireEvent.keyDown(prev, { key: 'Enter' })
    expect(screen.getByTestId('sport-day-label')).toHaveTextContent('Today')
  })
  it('Visa som nås från flikraden och tillbaka, i TV-storlek', async () => {
    mountSport({}, { days: { [today]: [live] } })
    await screen.findByTestId('sport-hero')
    const options = within(screen.getByTestId('sport-view-as')).getAllByTestId('tv-segment-option')
    expect(document.querySelector(screen.getByTestId('sport-tab-follows').getAttribute('data-f-right')!)).toBe(options[0])
    expect(document.querySelector(options[0].getAttribute('data-f-left')!)).toBe(screen.getByTestId('sport-tab-follows'))
    expect(options.every((o) => o.getAttribute('tabindex') === '0' && o.hasAttribute('data-f'))).toBe(true)
    // Lika stor text som filterchipsen ungefär — inte de 16 enheterna från förut.
    expect(parseFloat(options[0].style.fontSize)).toBeGreaterThan(parseFloat(screen.getByTestId('sport-summary').style.fontSize) - 2)
    fireEvent.keyDown(options[1], { key: 'Enter' })
    expect(getSportSettings().view).toBe('feed')
  })
  it('lådornas listor ritar ringen innanför raden — sidorna klipps annars av rullningen', async () => {
    mountSport({}, { days: { [today]: [live] } })
    await screen.findByTestId('sport-hero')
    const css = [...document.querySelectorAll('style')].map((s) => s.textContent ?? '').join('\n')
    expect(css).toMatch(/\[data-sport-stage\] \[data-panel-root\] \[data-f\]:focus[^{]*\{ outline-offset: -2px !important; \}/)
  })
  it('en äldre app utan endpointen får ett besked, inte en evig laddning', async () => {
    mountSport({}, { days: 'missing' })
    expect(await screen.findByTestId('sport-missing')).toHaveTextContent('Sport needs a newer version of Lumio.')
  })
  it('Titta i hero spelar bästa källan', async () => {
    mountSport({}, { days: { [today]: [live] } })
    fireEvent.click(await screen.findByTestId('sport-hero-watch'))
    expect(await screen.findByTestId('player')).toHaveTextContent('TV4 Fotboll FHD SE')
  })
  it('kortet öppnar matchcentret; Fel kanal? sparar åsidosättningen; Bakåt stänger lager för lager', async () => {
    const { onNavigate } = mountSport({}, { days: { [today]: [live, later] } })
    await screen.findByTestId('sport-hero')
    fireEvent.click(within(screen.getByTestId('sport-strip')).getAllByTestId('sport-card').find((c) => c.getAttribute('data-match-id') === 'later')!)
    expect(await screen.findByTestId('match-center')).toBeInTheDocument()
    fireEvent.click(screen.getByTestId('mc-pick-channel'))
    fireEvent.click(await screen.findByTestId('picker-row-A'))
    expect(getOverrides().later?.name).toBe('A')
    await waitFor(() => expect(screen.queryByTestId('channel-picker')).toBeNull())
    fireEvent.keyDown(window, { key: 'Escape' })
    await waitFor(() => expect(screen.queryByTestId('match-center')).toBeNull())
    expect(onNavigate).not.toHaveBeenCalled()
  })
  it('rälsens Sport-post navigerar till sportvyn', async () => {
    const { onNavigate } = mountSport({ view: 'hub' }, { days: {} })
    fireEvent.click(screen.getByTestId('rail-sport'))
    expect(onNavigate).toHaveBeenCalledWith({ pageId: 'live-tv-browse', params: { view: 'sport' } })
  })
})
